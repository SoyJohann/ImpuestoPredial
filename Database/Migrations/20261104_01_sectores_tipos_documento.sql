-- Migración aditiva para clasificar documentos por sector y tipo.
-- Aplicar una vez por base municipal, después de respaldarla.
-- Las columnas codigo_predial y archivo se conservan durante la transición de Dapper.

BEGIN;

CREATE TABLE IF NOT EXISTS sectores (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo character varying(60) NOT NULL UNIQUE,
    nombre character varying(120) NOT NULL,
    activo boolean NOT NULL DEFAULT true
);

INSERT INTO sectores (codigo, nombre)
VALUES
    ('PREDIAL', 'Predial'),
    ('INDUSTRIA_COMERCIO', 'Industria y Comercio')
ON CONFLICT (codigo) DO NOTHING;

CREATE TABLE IF NOT EXISTS tipos_documento (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sector_id integer NOT NULL REFERENCES sectores(id),
    codigo character varying(60) NOT NULL,
    nombre character varying(160) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_tipos_documento_sector_codigo UNIQUE (sector_id, codigo)
);

INSERT INTO tipos_documento (sector_id, codigo, nombre)
SELECT s.id, 'POR_CLASIFICAR', 'Por clasificar'
FROM sectores s
WHERE s.codigo IN ('PREDIAL', 'INDUSTRIA_COMERCIO')
ON CONFLICT (sector_id, codigo) DO NOTHING;

ALTER TABLE documentos
    ADD COLUMN IF NOT EXISTS tipo_documento_id integer,
    ADD COLUMN IF NOT EXISTS ruta character varying;

-- Los documentos existentes pertenecen al sector Predial y quedan pendientes
-- de clasificación específica porque el listado actual no conserva esa categoría.
UPDATE documentos d
SET tipo_documento_id = td.id
FROM sectores s
JOIN tipos_documento td
  ON td.sector_id = s.id
 AND td.codigo = 'POR_CLASIFICAR'
WHERE s.codigo = 'PREDIAL'
  AND d.tipo_documento_id IS NULL;

UPDATE documentos
SET ruta = archivo
WHERE ruta IS NULL;

ALTER TABLE documentos
    ALTER COLUMN tipo_documento_id SET NOT NULL;

DO $migration$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_documentos_tipo_documento'
          AND conrelid = 'documentos'::regclass
    ) THEN
        ALTER TABLE documentos
            ADD CONSTRAINT fk_documentos_tipo_documento
            FOREIGN KEY (tipo_documento_id) REFERENCES tipos_documento(id);
    END IF;
END
$migration$;

COMMIT;
